CREATE TABLE IF NOT EXISTS reward_requests (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kid TEXT NOT NULL, reward TEXT, title TEXT NOT NULL, emoji TEXT, cost INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', requested_at TEXT NOT NULL, decided_at TEXT
);
CREATE TABLE IF NOT EXISTS photos (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  data TEXT NOT NULL, mime TEXT NOT NULL DEFAULT 'image/jpeg', w INTEGER, h INTEGER,
  added_by TEXT, created_at TEXT NOT NULL, hidden INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS push_subs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  endpoint TEXT NOT NULL UNIQUE, p256dh TEXT NOT NULL, auth TEXT NOT NULL,
  who TEXT, prefs TEXT NOT NULL DEFAULT '[]', created_at TEXT NOT NULL, last_ok TEXT
);
