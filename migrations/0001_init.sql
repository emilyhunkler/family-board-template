CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL, updated_at TEXT);
CREATE TABLE IF NOT EXISTS checks (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  date TEXT NOT NULL, kid TEXT NOT NULL, task TEXT NOT NULL,
  points INTEGER NOT NULL DEFAULT 1, kind TEXT NOT NULL DEFAULT 'chore',
  done_at TEXT NOT NULL, by TEXT,
  UNIQUE(date, kid, task)
);
CREATE INDEX IF NOT EXISTS checks_date ON checks(date);
CREATE TABLE IF NOT EXISTS quest_claims (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  date TEXT NOT NULL, kid TEXT NOT NULL, quest TEXT, title TEXT NOT NULL, stars INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', claimed_at TEXT NOT NULL, decided_at TEXT
);
CREATE TABLE IF NOT EXISTS todos (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  date TEXT NOT NULL, kid TEXT, title TEXT NOT NULL, stars INTEGER NOT NULL DEFAULT 1,
  done_at TEXT, done_by TEXT, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ledger (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  week TEXT NOT NULL, kid TEXT NOT NULL, kind TEXT NOT NULL, amount REAL NOT NULL DEFAULT 0,
  stars INTEGER NOT NULL DEFAULT 0, note TEXT, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS groceries (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  text TEXT NOT NULL, aisle TEXT NOT NULL DEFAULT 'other', added_by TEXT, added_at TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 0, done_at TEXT
);
CREATE TABLE IF NOT EXISTS meals (date TEXT PRIMARY KEY, text TEXT NOT NULL, who TEXT, emoji TEXT, ingredients TEXT);
CREATE TABLE IF NOT EXISTS notes (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  text TEXT NOT NULL, from_who TEXT, created_at TEXT NOT NULL, expires_at TEXT
);
CREATE TABLE IF NOT EXISTS cache (key TEXT PRIMARY KEY, value TEXT NOT NULL, fetched_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS events_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT, at TEXT NOT NULL, kind TEXT NOT NULL, kid TEXT, text TEXT NOT NULL
);
